"""Restore the released SQLite retrieval snapshots into a clean checkout."""

import argparse
import gzip
from hashlib import sha256
import json
import os
from pathlib import Path
from tempfile import NamedTemporaryFile


DATABASES = ("library.sqlite3", "geometry.sqlite3")


def restore(root):
    catalog = root / "catalog"
    snapshots = catalog / "snapshots"
    manifest = json.loads((snapshots / "manifest.json").read_text(encoding="utf-8"))
    for name in DATABASES:
        destination = catalog / name
        if destination.exists():
            print(f"Keeping existing {destination.name}")
            continue

        expected = manifest[name]
        staged = None
        try:
            with gzip.open(snapshots / f"{name}.gz", "rb") as compressed:
                with NamedTemporaryFile(dir=catalog, suffix=".part", delete=False) as output:
                    staged = Path(output.name)
                    digest = sha256()
                    size = 0
                    for data in iter(lambda: compressed.read(1024 * 1024), b""):
                        size += len(data)
                        if size > expected["bytes"]:
                            raise ValueError(f"Snapshot exceeds expected size: {name}")
                        digest.update(data)
                        output.write(data)
            if size != expected["bytes"] or digest.hexdigest() != expected["sha256"]:
                raise ValueError(f"Snapshot checksum mismatch: {name}")
            # Create the final name without replacing an index generated by a concurrent invocation.
            try:
                if os.name == "nt":
                    staged.rename(destination)
                else:
                    destination.hardlink_to(staged)
            except FileExistsError:
                print(f"Keeping existing {destination.name}")
            else:
                print(f"Restored {destination.name}")
        finally:
            if staged is not None:
                staged.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    restore(parser.parse_args().root.resolve())


if __name__ == "__main__":
    main()
